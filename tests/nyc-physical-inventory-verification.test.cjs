const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const read = p => fs.readFileSync(p, 'utf8')

test('NYC physical stock is independent of mirrored catalog quantities', () => {
  const schema = read('prisma/schema.prisma')
  const migration = read('prisma/migrations/20261109004000_nyc_physical_stock_verification/migration.sql')
  assert.match(schema, /model NycPhysicalStockVerification/)
  assert.match(schema, /itemSlug String @id/)
  assert.match(schema, /verifiedQuantity Int @default\(0\)/)
  assert.match(migration, /NycPhysicalStockVerification_quantity_check/)
  assert.match(migration, /NycPhysicalStockVerification_status_check/)
  assert.match(migration, /NycPhysicalStockVerification_source_check/)
  const api = read('app/api/admin/nyc-physical-inventory/route.ts')
  assert.match(api, /prisma\.\$transaction\(async tx =>/)
  assert.match(api, /await lockNycCapacity\(tx\)/)
  assert.match(api, /tx\.nycPhysicalStockVerification\.upsert/)
  assert.match(api, /tx\.item\.findUnique/)
  assert.doesNotMatch(api, /prisma\.item\.(?:update|upsert|delete|create)/)
  assert.doesNotMatch(api, /sendEmail\(|paymentIntents|checkout\/charge/)
})

test('NYC stock verification requires NYC admin and same NYC origin for changes', () => {
  const src = read('app/api/admin/nyc-physical-inventory/route.ts')
  assert.match(src, /getServerSession\(authOptions\)/)
  assert.match(src, /role !== 'admin'/)
  assert.match(src, /https:\/\/friendlypartyrentalnyc\.com/)
  assert.match(src, /ALLOWED_NYC_ORIGINS\.has\(origin\)/)
  assert.match(src, /new URL\(origin\)\.hostname !== request\.nextUrl\.hostname/)
  assert.match(src, /Number\.isSafeInteger\(verifiedQuantity\)/)
  assert.match(src, /status === 'confirmed' && \(quantity < 1 \|\| source === 'unknown'\)/)
  assert.match(src, /status === 'unavailable' && quantity !== 0/)
})

test('NYC admin verification makes source/quantity explicit, does not claim readiness from catalog', () => {
  const page = read('app/admin/inventory/physical-verification/page.tsx')
  const component = read('components/admin/NycInventoryVerificationManager.tsx')
  const settings = read('app/admin/settings/nyc-launch-readiness/page.tsx')
  const items = read('app/admin/items/page.tsx')
  assert.match(page, /getServerSession/)
  assert.match(component, /Catalog quantities below are imported from Syracuse/)
  assert.match(component, /Supplier committed \/ confirmed/)
  assert.match(component, /Marking an item unavailable blocks online availability and checkout/)
  assert.match(component, /The catalog quantity itself was not edited/)
  assert.match(component, /NYC-owned \/ physically staged/)
  assert.match(settings, /\/admin\/inventory\/physical-verification/)
  assert.match(items, /\/admin\/inventory\/physical-verification/)
  assert.doesNotMatch(component, /paymentIntents\.create|stripe\.refunds|Syracuse inventory available for NYC/)
})
